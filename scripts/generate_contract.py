"""Generate frontend domain types from the canonical Pydantic JSON Schema."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.domain import Ticket


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(typescript(part) for part in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object":
        required = schema.get("required", [])
        return "{\n" + "\n".join(f"  {name}{'' if name in required else '?'}: {typescript(value)};" for name, value in schema["properties"].items()) + "\n}"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}[kind]


schema = Ticket.model_json_schema()
out = ROOT / "frontend" / "src" / "generated"
out.mkdir(parents=True, exist_ok=True)
definitions = schema.get("$defs", {}) | {"Ticket": schema}
content = "// Generated by scripts/generate_contract.py. Edit backend/app/domain.py instead.\n"
content += "\n\n".join(f"export type {name} = {typescript(value)};" for name, value in definitions.items())
areas = schema["properties"]["product_area"]["enum"]
content += "\n\nexport const PRODUCT_AREAS = " + json.dumps(areas) + " as const;\n"
(out / "schema.ts").write_text(content, encoding="utf-8")
(out / "ticket.schema.json").write_text(json.dumps(schema, indent=2) + "\n", encoding="utf-8")
print("Generated frontend ticket contract from Pydantic.")
